class Command(BaseCommand):
    help = "Seed DailyContent for a year"

    def handle(self, *args, **options):
        today = date.today()
        created = 0
        for i in range(365):
            d = today + timedelta(days=i - 30)
            if DailyContent.objects.filter(date=d).exists():
                continue
            idx = (d.toordinal()) % 10
            DailyContent.objects.create(
                date=d,
                tip=TIPS[idx % len(TIPS)],
                fact=FACTS[(idx + 3) % len(FACTS)],
                quote=QUOTES[(idx + 5) % len(QUOTES)][0],
                quote_author=QUOTES[(idx + 5) % len(QUOTES)][1],
                challenge=CHALLENGES[(idx + 7) % len(CHALLENGES)],
            )
            created += 1
        self.stdout.write(self.style.SUCCESS(f"Created {created} daily contents"))
